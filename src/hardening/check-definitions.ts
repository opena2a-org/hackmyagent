/**
 * What each check detects, why it matters and how to fix it, keyed by check
 * id. `explain <id>` answers from this table and `check-metadata` takes each
 * check's name from it, so neither prints a bare id or a generic
 * "<Category> finding." line for a check the tool reports.
 *
 * The scanners build each finding inline where they push it. The entries in
 * PUSHED_CHECKS copy the name, description, guidance (`why`) and fix from
 * those push sites; where a site builds a value from what it found (a file
 * name, a matched key, a count), the entry states it in general terms. `fix`
 * is absent where no push site gives one. `altNames` lists the other names a
 * site pushes the same id under: a variant of the finding, or the record a
 * passing check writes.
 *
 * __tests__/cli/explain-covers-check-metadata.test.ts walks the push sites
 * and fails when a pushed id is missing here, or is pushed under a name this
 * table does not list, so the table and the scanners cannot drift apart.
 */
