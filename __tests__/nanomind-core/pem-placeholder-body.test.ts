/**
 * A PEM private-key armor header framing a placeholder or a redaction is not a
 * private key.
 *
 * The PEM private-key shape matched the armor header alone, so a README, a
 * config template or a log line holding
 *
 *     -----BEGIN RSA PRIVATE KEY-----
 *     <your private key here>
 *     -----END RSA PRIVATE KEY-----
 *
 * was reported as AST-CRED-003 "PEM private key", the finding a real key gets.
 *
 * The rule: a hit is dropped only when an END marker begins within 4096
 * characters after the header and fewer than 40 base64-alphabet characters lie
 * between. Every other header is kept: a real key, a key cut off after its
 * first body line, a header with no END marker in reach. The rows below pin
 * both sides of each bound. Linear scan time on 1 MB of hostile PEM input is
 * timed in `openai-style-sk-key.test.ts`, with the other canonical shapes.
 *
 * The private keys are generated per run and are not secrets. Armor lines are
 * assembled from parts so this file holds no complete one.
 */

import { generateKeyPairSync } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { describe, it, expect } from 'vitest';

import {
  scanCanonicalCredentialFormatsForTest,
  analyzeCredentialKeywordContext,
} from '../../src/nanomind-core/compiler/semantic-compiler';
import { runNanoMindScan } from '../../src/nanomind-core/scanner-bridge';
import { tempDir } from '../helpers/temp-dir';

const PEM_LABEL = 'PEM private key';
const BEGIN = (kind: string) => '-----B' + `EGIN ${kind}PRIVATE KEY-----`;
const END = (kind: string) => '-----E' + `ND ${kind}PRIVATE KEY-----`;

const pemHits = (content: string) =>
  scanCanonicalCredentialFormatsForTest(content).filter(h => h.label === PEM_LABEL);

/** A block under the `kind` armor with `body` between the lines. */
const block = (body: string, kind = 'RSA ') => `${BEGIN(kind)}\n${body}\n${END(kind)}\n`;

/** A config holding `text` as a YAML block scalar; its first line is line 3. */
function configWith(text: string): string {
  const indented = text.trimEnd().split('\n').map(l => `  ${l}`).join('\n');
  return ['service: signer', 'private_key: |', indented, ''].join('\n');
}

/** Real private keys of every armor the shape names that Node can write. */
function realKeys(): Array<[string, string]> {
  const rsa = generateKeyPairSync('rsa', { modulusLength: 2048 }).privateKey;
  const ec = generateKeyPairSync('ec', { namedCurve: 'prime256v1' }).privateKey;
  const ed = generateKeyPairSync('ed25519').privateKey;
  return [
    ['RSA PKCS#1', rsa.export({ type: 'pkcs1', format: 'pem' }) as string],
    ['RSA PKCS#8', rsa.export({ type: 'pkcs8', format: 'pem' }) as string],
    ['EC SEC1', ec.export({ type: 'sec1', format: 'pem' }) as string],
    ['Ed25519 PKCS#8, the smallest', ed.export({ type: 'pkcs8', format: 'pem' }) as string],
    ['encrypted PKCS#8', rsa.export({ type: 'pkcs8', format: 'pem', cipher: 'aes-256-cbc', passphrase: 'p' }) as string],
  ];
}

describe('a PEM private-key header framing a placeholder or a redaction is not a hit', () => {
  const placeholders: Array<[string, string]> = [
    ['an angle-bracket placeholder', '<your private key here>'],
    ['an upper-case placeholder', '<YOUR_RSA_PRIVATE_KEY_GOES_HERE>'],
    ['an ellipsis', '...'],
    ['a redaction marker', '[REDACTED]'],
    ['a row of asterisks', '*'.repeat(64)],
    ['an empty body', ''],
    ['a short sentence', 'Paste the key generated by ssh-keygen here.'],
  ];
  for (const [name, body] of placeholders) {
    it(`${name} between the lines`, () => {
      expect(pemHits(block(body))).toEqual([]);
      expect(pemHits(configWith(block(body)))).toEqual([]);
    });
  }

  it('under every armor the shape names', () => {
    for (const kind of ['', 'RSA ', 'EC ', 'DSA ', 'OPENSSH ', 'ENCRYPTED ']) {
      expect(pemHits(block('<your private key here>', kind)), kind || 'bare').toEqual([]);
    }
  });

  it('on one line, as a JSON string holds it', () => {
    const content = JSON.stringify({ key: `${BEGIN('')}\n...\n${END('')}\n` });
    expect(content).not.toContain('\n');
    expect(pemHits(content)).toEqual([]);
  });

  it('the keyword-context path reads the same rule through its own loop', () => {
    // `{"token": null}` makes the content schema-only unless a canonical
    // format is present, so the answer is decided by the PEM shape alone.
    expect(analyzeCredentialKeywordContext(`{"token": null}\n${block('...')}`)).toBe('schema-only');
    expect(analyzeCredentialKeywordContext(`{"token": null}\n${realKeys()[0][1]}`)).toBe('value-present');
  });
});

describe('a real or truncated key is still a hit', () => {
  for (const [name, pem] of realKeys()) {
    it(`a generated ${name} key`, () => {
      expect(pemHits(pem)).toHaveLength(1);
      expect(pemHits(configWith(pem))).toHaveLength(1);
    });
  }

  it('a key cut off after its first body line, before its END marker', () => {
    const [header, first] = realKeys()[0][1].split('\n');
    expect(pemHits(`${header}\n${first}\n...\n${END('RSA ')}\n`)).toHaveLength(1);
  });

  it('a key cut off with no END marker at all', () => {
    const [header, first, second] = realKeys()[0][1].split('\n');
    expect(pemHits(`${header}\n${first}\n${second}\n`)).toHaveLength(1);
  });

  it('a header alone, with nothing after it', () => {
    expect(pemHits(BEGIN('RSA '))).toHaveLength(1);
    expect(pemHits(`${BEGIN('RSA ')}\n`)).toHaveLength(1);
  });

  it('each header of two consecutive real keys', () => {
    const [, pem] = realKeys()[0];
    expect(pemHits(`${pem}\n${pem}`)).toHaveLength(2);
  });
});

describe('the two bounds', () => {
  const header = BEGIN('RSA ');

  it('39 base64-alphabet characters before the END marker is a placeholder, 40 is a key', () => {
    // Spaces and punctuation are not counted, so the count is exact.
    const body = (n: number) => 'Ab+/'.repeat(10).slice(0, n).split('').join(' ');
    expect(pemHits(`${header}\n${body(39)}\n${END('RSA ')}`)).toEqual([]);
    expect(pemHits(`${header}\n${body(40)}\n${END('RSA ')}`)).toHaveLength(1);
  });

  it('padding and line breaks are not alphabet characters', () => {
    expect(pemHits(`${header}\n${'=\n'.repeat(200)}${END('RSA ')}`)).toEqual([]);
  });

  it('an END marker beginning 4095 characters after the header closes it, one at 4096 does not', () => {
    const at = (offset: number) => `${header}${'.'.repeat(offset)}${END('RSA ')}`;
    expect(pemHits(at(4095))).toEqual([]);
    expect(pemHits(at(4096))).toHaveLength(1);
  });

  it('a dash run, or dashes before a word that only starts with END, is not an END marker', () => {
    expect(pemHits(`${header}\n${'-'.repeat(100)}\n`)).toHaveLength(1);
    expect(pemHits(`${header}\n-----E` + `NDING\n`)).toHaveLength(1);
  });
});

describe('end to end: AST-CRED-003', () => {
  async function credFindings(content: string) {
    const dir = tempDir('hma-pem-placeholder-');
    await writeFile(join(dir, 'config.yaml'), content, 'utf-8');
    const result = await runNanoMindScan(dir, []);
    return result.mergedFindings.filter(
      f => !f.passed && f.checkId === 'AST-CRED-003' && f.message.includes(PEM_LABEL),
    );
  }

  it('a config holding a placeholder block gets no PEM private key finding', async () => {
    expect(await credFindings(configWith(block('<your private key here>')))).toEqual([]);
  });

  it('control: the same config holding a real key gets one, on the header line', async () => {
    const cred = await credFindings(configWith(realKeys()[0][1]));
    expect(cred).toHaveLength(1);
    expect(cred[0].file).toBe('config.yaml');
    expect(cred[0].line).toBe(3);
  });
});
